EXTRACTION_MAX_TOKENS = 4096

class ExtractionFormatError(ValueError):
    """A response failed the common extraction contract; no raw text exposed."""

class ExtractionTruncatedError(ExtractionFormatError):
    pass


def instructions_for(task, *, reply_mode="answer"):
    if task == "private":
        return BASE_INSTRUCTIONS + PRIVATE_INSTRUCTIONS + dialogue_guidance(reply_mode)
    if task == "archive":
        return BASE_INSTRUCTIONS + ARCHIVE_INSTRUCTIONS
    if task == "search":
        return SEARCH_INSTRUCTIONS
    if task == "extraction":
        return EXTRACTION_INSTRUCTIONS
    raise ValueError("Unknown AI task")


def parse_extraction(text, finish_reason=None):
    if finish_reason in ("length", "MAX_TOKENS"):
        raise ExtractionTruncatedError("Extraction output was truncated")
    if not isinstance(text, str) or not text.strip() or len(text) > 65536:
        raise ExtractionFormatError("Missing or oversized extraction output")
    def reject_constant(value):
        raise ExtractionFormatError("Non-finite JSON number")
    def unique_object(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ExtractionFormatError("Duplicate JSON field")
            result[key] = value
        return result
    try:
        raw = json.loads(text, parse_constant=reject_constant, object_pairs_hook=unique_object)
        split_dialog_extraction(raw)
    except (ValueError, TypeError, RecursionError) as error:
        raise ExtractionFormatError("Invalid extraction JSON or envelope") from error
    return raw


def finalize_memory_answer(answer, diagnostics):
    """Never deliver a generated persistence claim after a failed write."""
    # Keep a useful ordinary answer if it does not claim a persistence action.
    # Shared model instructions prohibit such claims; this conservative guard
    # also blocks the concrete confirmations observed in live acceptance.
    claims_write = bool(re.search(
        r"\b(?:сохранил[аои]?|сохранен[аоы]?|запомнил[аои]?|записал[аои]?|"
        r"обновил[аои]?|обновлен[аоы]?|запомнено|записано)\b",
        answer.casefold().replace("ё", "е")))
    if diagnostics.get("write_status") == "ошибка" and claims_write:
        return "Сохранить новые сведения в памяти сейчас не удалось. Попробуем позже."
    return answer


